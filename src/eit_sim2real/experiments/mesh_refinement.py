"""Mesh-refinement cross-evaluation experiment.

Evaluates the production-trained CNNs against a test set generated at a
DIFFERENT forward-model mesh refinement than the one used to produce the
training data. Provides direct evidence on whether noise-augmentation
results transfer across forward-model discretisation fidelity.

Motivation (Section 5.2, Section 5.6 of the dissertation)
---------------------------------------------------------
The mesh convergence study (matlab/validate_mesh_convergence.m) showed
that switching from coarse ('c') to fine ('f') refinement induces an
8-18% relative voltage shift for spatially-extended classes and a
sub-mesh-scale regime for the point class. A purely in-mesh evaluation
cannot rule out that the headline noisy-CNN robustness result is partly
an artefact of the mesh choice. This experiment loads the existing
noisy-trained CNN, applies it to a fine-mesh test set generated by
matlab/generate_mesh_refinement_testset.m, and reports the resulting
accuracy alongside the published in-mesh baseline.

Pipeline
--------
1. Load the production training dataset (data/eit_dataset.mat) and
   refit the RobustScaler exactly as the original training did
   (prepare_splits with the same random_state). This recovers the
   scaler the saved model expects.
2. Load the fine-mesh test set (data/eit_dataset_mesh_<r>.mat).
3. Apply the production scaler to the fine-mesh voltage vectors.
4. Run the saved CNN against the scaled fine-mesh test set. Report
   overall accuracy, macro F1, per-class accuracy, and the drop
   relative to the in-mesh test-split baseline.
5. (Optional) Also run the clean-trained CNN as a control. This row
   should remain near chance, confirming that the mesh-refinement
   axis does not accidentally bridge the sim-to-real gap by itself.

Outputs are written to results/additional_experiments/mesh_refinement/
results.json. See README in that folder (auto-created on first run).
"""

from __future__ import annotations

import json
import logging
from pathlib import Path
from typing import Any

import numpy as np
import torch
from sklearn.metrics import accuracy_score

from eit_sim2real.constants import CLASS_NAMES, NUM_CLASSES
from eit_sim2real.data import load_mat_dataset, prepare_splits
from eit_sim2real.evaluate import evaluate_model
from eit_sim2real.models.cnn1d import EITConv1D
from eit_sim2real.utils import get_device, set_seeds

logger = logging.getLogger(__name__)


def _per_class_accuracy(y_true: np.ndarray, y_pred: np.ndarray) -> dict[str, float]:
    """Compute per-class accuracy as a name -> accuracy dict."""
    out: dict[str, float] = {}
    for cls_id, cls_name in enumerate(CLASS_NAMES):
        mask = y_true == cls_id
        if mask.sum() == 0:
            out[cls_name] = float("nan")
        else:
            out[cls_name] = float(accuracy_score(y_true[mask], y_pred[mask]))
    return out


def _fit_production_scaler(
    baseline_dataset_path: Path,
    use_noisy: bool,
    random_state: int = 42,
) -> tuple[Any, np.ndarray, np.ndarray]:
    """Reproduce the scaler fitted during production training.

    Returns the scaler plus the in-mesh test split (already scaled),
    so the caller can confirm the baseline accuracy matches the
    published figure before trusting the cross-mesh comparison.
    """
    X, y = load_mat_dataset(baseline_dataset_path, use_noisy=use_noisy)
    splits = prepare_splits(
        X,
        y,
        random_state=random_state,
        normalize=True,
        scaler_type="robust",
    )
    return splits.scaler, splits.X_test, splits.y_test


def _load_cnn(model_path: Path, n_features: int) -> EITConv1D:
    """Load a CNN1D checkpoint, raising a clear error if missing."""
    if not model_path.exists():
        raise FileNotFoundError(
            f"Model checkpoint not found: {model_path}. "
            "Run the main experiment grid first to produce trained CNNs."
        )
    model = EITConv1D(n_features=n_features, n_classes=NUM_CLASSES)
    model.load_state_dict(torch.load(model_path, weights_only=True))
    model.eval()
    return model


def run_mesh_refinement_evaluation(
    baseline_dataset_path: Path,
    fine_mesh_dataset_path: Path,
    noisy_model_path: Path,
    clean_model_path: Path | None = None,
    output_dir: Path | None = None,
    seed: int = 42,
) -> dict[str, Any]:
    """Cross-mesh evaluation of the production CNNs.

    Args:
        baseline_dataset_path: Production training dataset (coarse mesh).
            Used to refit the RobustScaler the saved models expect.
        fine_mesh_dataset_path: Test set generated at an alternative
            refinement by matlab/generate_mesh_refinement_testset.m.
        noisy_model_path: Path to cnn1d_noisy_best.pt (or equivalent).
        clean_model_path: Optional path to the clean-trained CNN for a
            control comparison. If None, the control row is skipped.
        output_dir: Where to write results.json. Defaults to
            results/additional_experiments/mesh_refinement/.
        seed: Random seed (matches the production training split).

    Returns:
        Dict summarising the experiment (also written to disk).
    """
    set_seeds(seed)
    device = get_device()

    logger.info("=" * 70)
    logger.info("MESH-REFINEMENT CROSS-EVALUATION")
    logger.info("=" * 70)
    logger.info(f"Baseline dataset:  {baseline_dataset_path}")
    logger.info(f"Fine-mesh dataset: {fine_mesh_dataset_path}")
    logger.info(f"Noisy CNN:         {noisy_model_path}")
    if clean_model_path is not None:
        logger.info(f"Clean CNN:         {clean_model_path}")

    # ── 1. Refit the production scalers and recover in-mesh test splits ──
    logger.info("\n[1/4] Refitting production scalers...")
    noisy_scaler, X_test_in_noisy, y_test_in_noisy = _fit_production_scaler(
        baseline_dataset_path, use_noisy=True, random_state=seed
    )
    clean_scaler = None
    X_test_in_clean = y_test_in_clean = None
    if clean_model_path is not None:
        clean_scaler, X_test_in_clean, y_test_in_clean = _fit_production_scaler(
            baseline_dataset_path, use_noisy=False, random_state=seed
        )

    # ── 2. Load the fine-mesh test set ──
    logger.info("\n[2/4] Loading fine-mesh test set...")
    if not fine_mesh_dataset_path.exists():
        raise FileNotFoundError(
            f"Fine-mesh test set not found: {fine_mesh_dataset_path}. "
            "Generate it first by running, in MATLAB:\n"
            "  generate_mesh_refinement_testset()"
        )
    X_fine_clean_raw, y_fine = load_mat_dataset(fine_mesh_dataset_path, use_noisy=False)
    X_fine_noisy_raw, y_fine_check = load_mat_dataset(
        fine_mesh_dataset_path, use_noisy=True
    )
    if not np.array_equal(y_fine, y_fine_check):
        raise ValueError(
            "Clean and noisy label vectors disagree in the fine-mesh "
            "dataset; the .mat file appears corrupt."
        )
    logger.info(
        f"  Loaded {X_fine_noisy_raw.shape[0]} samples, "
        f"{X_fine_noisy_raw.shape[1]} features"
    )

    # Feature-dimension sanity check (mesh refinement must not change
    # the measurement count for a given electrode configuration).
    n_features = X_test_in_noisy.shape[1]
    if X_fine_noisy_raw.shape[1] != n_features:
        raise ValueError(
            f"Feature-count mismatch: baseline has {n_features} features, "
            f"fine-mesh test set has {X_fine_noisy_raw.shape[1]}. "
            "Check that both datasets use the same electrode count and "
            "drive pattern."
        )

    # ── 3. Apply production scalers to the fine-mesh data ──
    logger.info("\n[3/4] Applying production scalers to fine-mesh data...")
    X_fine_noisy = noisy_scaler.transform(X_fine_noisy_raw).astype(np.float32)
    X_fine_clean = (
        clean_scaler.transform(X_fine_clean_raw).astype(np.float32)
        if clean_scaler is not None
        else None
    )

    # ── 4. Evaluate ──
    logger.info("\n[4/4] Evaluating models...")
    noisy_model = _load_cnn(noisy_model_path, n_features)

    # Sanity-check the noisy CNN on the in-mesh test split first.
    logger.info("  Noisy CNN, in-mesh test split (sanity check)...")
    in_mesh_noisy = evaluate_model(
        noisy_model, X_test_in_noisy, y_test_in_noisy, device=device
    )

    # Cross-mesh evaluations.
    logger.info("  Noisy CNN, fine-mesh noisy test set...")
    cross_noisy = evaluate_model(noisy_model, X_fine_noisy, y_fine, device=device)
    logger.info("  Noisy CNN, fine-mesh CLEAN test set (control)...")
    cross_noisy_on_clean = evaluate_model(
        noisy_model,
        noisy_scaler.transform(X_fine_clean_raw).astype(np.float32),
        y_fine,
        device=device,
    )

    summary: dict[str, Any] = {
        "experiment": "mesh_refinement_cross_evaluation",
        "description": (
            "Evaluates the production-trained CNN(s) on a test set "
            "generated at a different forward-model mesh refinement. "
            "Tests whether the noise-augmentation result transfers "
            "across discretisation fidelity (Section 5.2)."
        ),
        "baseline_dataset": str(baseline_dataset_path),
        "fine_mesh_dataset": str(fine_mesh_dataset_path),
        "seed": seed,
        "n_features": int(n_features),
        "fine_mesh_n_samples": int(X_fine_noisy_raw.shape[0]),
        "noisy_cnn": {
            "checkpoint": str(noisy_model_path),
            "in_mesh_noisy": {
                "accuracy": in_mesh_noisy["accuracy"],
                "f1_macro": in_mesh_noisy["f1_macro"],
                "per_class_accuracy": _per_class_accuracy(
                    y_test_in_noisy, in_mesh_noisy["y_pred"]
                ),
                "n_samples": int(y_test_in_noisy.shape[0]),
            },
            "cross_mesh_noisy": {
                "accuracy": cross_noisy["accuracy"],
                "f1_macro": cross_noisy["f1_macro"],
                "per_class_accuracy": _per_class_accuracy(
                    y_fine, cross_noisy["y_pred"]
                ),
                "n_samples": int(y_fine.shape[0]),
            },
            "cross_mesh_clean_control": {
                "accuracy": cross_noisy_on_clean["accuracy"],
                "f1_macro": cross_noisy_on_clean["f1_macro"],
                "per_class_accuracy": _per_class_accuracy(
                    y_fine, cross_noisy_on_clean["y_pred"]
                ),
                "n_samples": int(y_fine.shape[0]),
                "note": (
                    "Noisy CNN evaluated on clean (un-noised) fine-mesh "
                    "voltages. Isolates pure mesh-shift effect from the "
                    "additional MATLAB noise realisation."
                ),
            },
            "accuracy_drop_in_minus_cross": float(
                in_mesh_noisy["accuracy"] - cross_noisy["accuracy"]
            ),
        },
    }

    # Optional control: clean CNN on the fine-mesh noisy test set.
    if clean_model_path is not None and X_fine_clean is not None:
        clean_model = _load_cnn(clean_model_path, n_features)
        logger.info("  Clean CNN, in-mesh test split (sanity check)...")
        in_mesh_clean = evaluate_model(
            clean_model, X_test_in_clean, y_test_in_clean, device=device
        )
        # Noisy test set must use the clean-trained scaler too (since the
        # clean CNN was normalised against clean training statistics).
        X_fine_noisy_clean_scaled = clean_scaler.transform(X_fine_noisy_raw).astype(
            np.float32
        )
        logger.info("  Clean CNN, fine-mesh noisy test set...")
        cross_clean = evaluate_model(
            clean_model, X_fine_noisy_clean_scaled, y_fine, device=device
        )
        summary["clean_cnn"] = {
            "checkpoint": str(clean_model_path),
            "in_mesh_clean": {
                "accuracy": in_mesh_clean["accuracy"],
                "f1_macro": in_mesh_clean["f1_macro"],
                "per_class_accuracy": _per_class_accuracy(
                    y_test_in_clean, in_mesh_clean["y_pred"]
                ),
                "n_samples": int(y_test_in_clean.shape[0]),
            },
            "cross_mesh_noisy": {
                "accuracy": cross_clean["accuracy"],
                "f1_macro": cross_clean["f1_macro"],
                "per_class_accuracy": _per_class_accuracy(
                    y_fine, cross_clean["y_pred"]
                ),
                "n_samples": int(y_fine.shape[0]),
                "note": (
                    "Expected near chance level — confirms mesh shift "
                    "alone does not bridge the sim-to-real gap."
                ),
            },
        }

    # ── Console summary ──
    logger.info("\n" + "=" * 70)
    logger.info("RESULTS")
    logger.info("=" * 70)
    n = summary["noisy_cnn"]
    logger.info(
        f"Noisy CNN  | in-mesh noisy:     {n['in_mesh_noisy']['accuracy']:.4f} "
        f"({n['in_mesh_noisy']['n_samples']} samples)"
    )
    logger.info(
        f"Noisy CNN  | cross-mesh noisy:  {n['cross_mesh_noisy']['accuracy']:.4f} "
        f"({n['cross_mesh_noisy']['n_samples']} samples)"
    )
    logger.info(
        f"           | drop (in - cross): {n['accuracy_drop_in_minus_cross']:+.4f}"
    )
    logger.info(
        f"Noisy CNN  | cross-mesh clean control: "
        f"{n['cross_mesh_clean_control']['accuracy']:.4f}"
    )
    if "clean_cnn" in summary:
        c = summary["clean_cnn"]
        logger.info(
            f"Clean CNN  | in-mesh clean:     {c['in_mesh_clean']['accuracy']:.4f}"
        )
        logger.info(
            f"Clean CNN  | cross-mesh noisy:  {c['cross_mesh_noisy']['accuracy']:.4f} "
            "(expected near chance)"
        )

    # Per-class table for the noisy CNN.
    logger.info("\nNoisy CNN — per-class accuracy (cross-mesh noisy):")
    for cls_name, acc in n["cross_mesh_noisy"]["per_class_accuracy"].items():
        logger.info(f"  {cls_name:<22s} {acc:.4f}")

    # Interpretation hint.
    drop = n["accuracy_drop_in_minus_cross"]
    if abs(drop) < 0.03:
        verdict = (
            "Within CV sampling noise (<3pp). The noise-augmentation "
            "result is robust to mesh refinement — strong evidence that "
            "the headline robustness result is not a mesh artefact."
        )
    elif drop < 0.10:
        verdict = (
            "Moderate drop (3-10pp). Noise-augmentation generalises "
            "across mesh refinement but with measurable sensitivity; "
            "worth disclosing in the dissertation."
        )
    else:
        verdict = (
            "Large drop (>10pp). The CNN is partly relying on "
            "mesh-specific signal statistics. Requires explicit "
            "discussion in the limitations section."
        )
    logger.info(f"\nInterpretation: {verdict}")
    summary["interpretation"] = verdict

    # ── Persist ──
    if output_dir is None:
        output_dir = Path("results/additional_experiments/mesh_refinement")
    output_dir.mkdir(parents=True, exist_ok=True)
    out_file = output_dir / "results.json"
    with open(out_file, "w") as f:
        json.dump(summary, f, indent=2)
    logger.info(f"\nResults saved to: {out_file}")

    return summary


def main(
    baseline_dataset: str = "data/eit_dataset.mat",
    fine_mesh_dataset: str = "data/eit_dataset_mesh_f.mat",
    noisy_model: str = "results/models/cnn1d_noisy_best.pt",
    clean_model: str | None = "results/models/cnn1d_clean_best.pt",
    output_dir: str | None = None,
    seed: int = 42,
) -> dict[str, Any]:
    """Entry point used by the CLI."""
    return run_mesh_refinement_evaluation(
        baseline_dataset_path=Path(baseline_dataset),
        fine_mesh_dataset_path=Path(fine_mesh_dataset),
        noisy_model_path=Path(noisy_model),
        clean_model_path=Path(clean_model) if clean_model else None,
        output_dir=Path(output_dir) if output_dir else None,
        seed=seed,
    )
